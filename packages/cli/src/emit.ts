/**
 * Quotes an object key only when it cannot be written bare.
 *
 * @param key - The property name.
 * @returns The key as it should appear in source.
 */
const propertyKey = (key: string): string =>
    /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);

/**
 * Prints a value as TypeScript source.
 *
 * Generated patches are reviewed by people, so this is a readable printer rather than
 * `JSON.stringify`: bare keys where possible, one entry per line, and a trailing comma
 * so adding the next attribute is a one-line diff. Key order is the caller's, which is
 * already deterministic (`diffModel` sorts), so regenerating the same model twice
 * produces the same file.
 *
 * @param value - Any JSON-serializable value.
 * @param indent - Current indentation, as literal spaces.
 * @returns The value as source, with no trailing newline.
 */
export const toSource = (value: unknown, indent = ""): string => {
    if (value === null) return "null";
    if (typeof value !== "object") return JSON.stringify(value);
    const inner = `${indent}    `;
    if (Array.isArray(value)) {
        if (!value.length) return "[]";
        const items = value.map(item => `${inner}${toSource(item, inner)},`);
        return `[\n${items.join("\n")}\n${indent}]`;
    }
    const entries = Object.entries(value as Record<string, unknown>)
        .filter(([, entry]) => entry !== undefined);
    if (!entries.length) return "{}";
    const lines = entries.map(
        ([key, entry]) => `${inner}${propertyKey(key)}: ${toSource(entry, inner)},`
    );
    return `{\n${lines.join("\n")}\n${indent}}`;
};

/**
 * Where a generated file imports the `Patch` type from.
 *
 * `@docstack/client/model` rather than `@docstack/shared`: shared is an internal package
 * that an application does not depend on, so a file importing it would not compile in a
 * project that installed the client and this CLI. The model entry is the pure one - no
 * engine, no storage layer - which is also what the model module itself imports.
 */
export const DEFAULT_TYPES_IMPORT = "@docstack/client/model";

/** Everything the generated patch module needs to state. */
export type PatchFileInput = {
    /** The patch's semver version, which is also its file name. */
    version: string;
    /** The consumer's patch target, which the sync gate reads alongside the version. */
    target: string;
    /** The `-m` message. */
    changelog: string;
    /** The delta documents, from `diffModel`. */
    docs: unknown[];
    /** Import specifier for the `Patch` type. Default {@link DEFAULT_TYPES_IMPORT}. */
    typesImport?: string;
};

/**
 * Renders a generated patch module.
 *
 * The one-shot job hooks are emitted commented out rather than omitted: a data
 * migration is the common reason to hand-edit a generated patch, and a stub names the
 * shape it has to take (ADR-0044).
 *
 * @param input - See {@link PatchFileInput}.
 * @returns The module source, newline-terminated.
 */
export const renderPatchFile = (input: PatchFileInput): string => {
    const identifier = `patch_${input.version.replace(/[.\-+]/g, "_")}`;
    return `import type { Patch } from "${input.typesImport ?? DEFAULT_TYPES_IMPORT}";

/**
 * ${input.changelog}
 *
 * Generated by \`docstack revision --autogenerate\`. Regenerate rather than hand-edit
 * the documents below; \`docstack revision --check\` compares them against the model.
 */
const ${identifier}: Patch = ${toSource({
        _id: `${input.target}-${input.version}`,
        "~class": "patch",
        target: input.target,
        version: input.version,
        changelog: input.changelog,
        docs: input.docs,
    })};

// A data migration goes here, by handler name rather than as source (proposal.md §6.4):
// ${identifier}.preApply = { name: "app.someBackfill", content: "", requiresKey: false };
// ${identifier}.postApply = { name: "app.someBackfill", content: "" };

export default ${identifier};
`;
};

/**
 * Renders the patch directory's index.
 *
 * The chain is an ordered array, so the index is generated rather than maintained:
 * every revision rewrites it, and the order is the one the engine applies in.
 *
 * @param versions - The versions present, already in semver order.
 * @param typesImport - Where to import the `Patch` type from; see
 * {@link DEFAULT_TYPES_IMPORT}.
 * @returns The module source, newline-terminated.
 */
export const renderIndexFile = (versions: readonly string[], typesImport?: string): string => {
    const names = versions.map(version => ({
        version,
        identifier: `patch_${version.replace(/[.\-+]/g, "_")}`,
    }));
    const imports = names
        .map(({ version, identifier }) => `import ${identifier} from "./${version}.js";`)
        .join("\n");
    const list = names.map(({ identifier }) => `    ${identifier},`).join("\n");
    return `import type { Patch } from "${typesImport ?? DEFAULT_TYPES_IMPORT}";
${imports}

/**
 * The application's patch chain, in the order it applies.
 *
 * Generated by \`docstack revision\`. Hand-editing this file is pointless: the next
 * revision rewrites it from the files present.
 */
export const patches: Patch[] = [
${list}
];

export default patches;
`;
};
