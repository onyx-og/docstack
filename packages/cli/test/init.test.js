import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import assert from "node:assert/strict";
import { init } from "../lib/init.js";

/**
 * Where throwaway projects are created: inside this package, so a scaffolded model's
 * imports resolve by walking up exactly as they would in a real application.
 */
const SCRATCH = join(dirname(fileURLToPath(import.meta.url)), ".tmp-init");

test.after(() => rmSync(SCRATCH, { recursive: true, force: true }));

/**
 * A throwaway project.
 *
 * @param manifest - What its package.json should say.
 * @param files - Extra files to create, keyed by relative path.
 */
const project = (manifest = { name: "probe-app" }, files = {}) => {
    mkdirSync(SCRATCH, { recursive: true });
    const root = mkdtempSync(join(SCRATCH, "proj-"));
    writeFileSync(join(root, "package.json"), JSON.stringify(manifest), "utf8");
    for (const [path, content] of Object.entries(files)) {
        mkdirSync(dirname(join(root, path)), { recursive: true });
        writeFileSync(join(root, path), content, "utf8");
    }
    return root;
};

// The starter model imports the builders, and the first patch is generated by loading it.
// Pointed at `@docstack/shared` so these tests need only this package's own dependency
// built, not the client - `@docstack/client/model` is the default for a real project.
const FROM_SHARED = { typesImport: "@docstack/shared" };

test("scaffolds a model, its first patch, the scripts and the agent section", () => {
    const root = project({ name: "probe-app" }, { "src/.keep": "" });
    const result = init({ cwd: root, ...FROM_SHARED });

    assert.equal(result.code, 0);
    // `src` exists, so the model goes in it rather than at the root.
    assert.ok(existsSync(join(root, "src", "model.ts")));
    assert.ok(existsSync(join(root, "src", "patches", "0.1.0.ts")));
    assert.ok(existsSync(join(root, "src", "patches", "index.ts")));

    // The generated patch really describes the starter model, rather than being a stub.
    const patch = readFileSync(join(root, "src", "patches", "0.1.0.ts"), "utf8");
    assert.match(patch, /_id: "Note"/);
    assert.match(patch, /target: "probe-app"/);

    const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
    assert.equal(manifest.scripts["revision:check"], "docstack revision --check");
    assert.equal(manifest.scripts["docstack:doctor"], "docstack doctor");

    // The section an agent reads says where the model is and what not to hand-edit.
    const agents = readFileSync(join(root, "AGENTS.md"), "utf8");
    assert.match(agents, /declared in code\*\* at `src\/model\.ts`/);
    assert.match(agents, /Never hand-edit/);
    assert.match(agents, /revision --check/);
});

test("puts the model at the root when there is no src", () => {
    const root = project();
    init({ cwd: root, ...FROM_SHARED });
    assert.ok(existsSync(join(root, "model.ts")));
    assert.ok(existsSync(join(root, "patches", "0.1.0.ts")));
});

test("a second run changes nothing it has already written", () => {
    const root = project({ name: "probe-app" }, { "src/.keep": "" });
    init({ cwd: root, ...FROM_SHARED });
    const modelBefore = readFileSync(join(root, "src", "model.ts"), "utf8");
    const agentsBefore = readFileSync(join(root, "AGENTS.md"), "utf8");

    const second = init({ cwd: root, ...FROM_SHARED });

    assert.equal(second.code, 0);
    // The model carries decisions, so a re-run must not eat them.
    assert.equal(readFileSync(join(root, "src", "model.ts"), "utf8"), modelBefore);
    // And the agent section is replaced in place, not appended again.
    const agentsAfter = readFileSync(join(root, "AGENTS.md"), "utf8");
    assert.equal(agentsAfter, agentsBefore);
    assert.equal(agentsAfter.split("<!-- docstack:begin -->").length - 1, 1);
    // No second patch for a model it did not write.
    assert.ok(!existsSync(join(root, "src", "patches", "0.2.0.ts")));
});

test("keeps a model that is already there, and generates no patch for it", () => {
    const own = `import { defineClass, defineModel, a } from "@docstack/shared";
export const Mine = defineClass("Mine", { attributes: { x: a.string({}) } });
export const model = defineModel({ classes: [Mine] });
`;
    const root = project({ name: "probe-app" }, { "src/model.ts": own });
    const result = init({ cwd: root, ...FROM_SHARED });

    assert.equal(readFileSync(join(root, "src", "model.ts"), "utf8"), own);
    assert.ok(!existsSync(join(root, "src", "patches", "0.1.0.ts")));
    assert.match(result.output.join("\n"), /Kept src\/model\.ts/);
    // It says how to find out whether the chain matches, rather than deciding.
    assert.match(result.output.join("\n"), /revision --check/);
});

test("preserves existing agent instructions and existing scripts", () => {
    const root = project(
        { name: "probe-app", scripts: { revision: "echo mine" } },
        { "AGENTS.md": "# probe-app\n\nMy own rules.\n" }
    );
    init({ cwd: root, ...FROM_SHARED });

    const agents = readFileSync(join(root, "AGENTS.md"), "utf8");
    assert.match(agents, /My own rules\./);
    assert.match(agents, /## DocStack/);

    // An existing script is the author's, not ours to replace.
    const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
    assert.equal(manifest.scripts.revision, "echo mine");
    assert.equal(manifest.scripts["revision:check"], "docstack revision --check");
});

test("the wiring it prints follows the project it found", () => {
    const reactRoot = project({ name: "r", dependencies: { react: "^19.0.0" } });
    const reactOut = init({ cwd: reactRoot, ...FROM_SHARED }).output.join("\n");
    assert.match(reactOut, /Detected a react project/);
    assert.match(reactOut, /StackProvider/);
    assert.match(reactOut, /@docstack\/react/);

    const nodeRoot = project({ name: "n", dependencies: { express: "^4.0.0" } });
    const nodeOut = init({ cwd: nodeRoot, ...FROM_SHARED }).output.join("\n");
    assert.match(nodeOut, /Detected a node project/);
    assert.match(nodeOut, /new DocStack/);
    assert.doesNotMatch(nodeOut, /@docstack\/react/);
});

test("refuses where there is no project", () => {
    mkdirSync(SCRATCH, { recursive: true });
    const root = mkdtempSync(join(SCRATCH, "bare-"));
    // Without a package.json there is nothing to set up, and the patch target has
    // nothing to default to.
    assert.throws(() => init({ cwd: root, ...FROM_SHARED }), /No package\.json/);
});
