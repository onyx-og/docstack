import semver from "semver";
import { ClassModel, Patch } from "../../../types.js";

/**
 * Merges a patch document's `schema` into the stored one, attribute by attribute.
 *
 * A class patch is a **delta, not a restatement** (ADR-0037, ADR-0038): an attribute the
 * patch does not mention stays as stored, and an explicit `null` entry drops it. A plain
 * object spread would replace the schema wholesale, which is the "lost attributes"
 * failure ADR-0037 describes.
 *
 * Mutates `doc.schema`, which is how both callers want it; `sourceDoc` is the patch's
 * own document and is never touched, because system patches are module-level objects
 * shared by every stack in the process.
 *
 * @param sourceDoc - The patch's document, as authored.
 * @param existingDoc - The document as stored (or as folded so far).
 * @param doc - The document being built, already spread from the two.
 */
export const mergePatchSchema = (sourceDoc: any, existingDoc: any, doc: any): void => {
    const incoming = sourceDoc?.schema;
    const stored = existingDoc?.schema;
    if (incoming && typeof incoming === "object" && !Array.isArray(incoming)
        && stored && typeof stored === "object" && !Array.isArray(stored)) {
        const merged: Record<string, unknown> = { ...stored, ...incoming };
        for (const name of Object.keys(incoming)) {
            if (incoming[name] === null) delete merged[name];
        }
        doc.schema = merged;
    }
};

/** What a patch chain produces, with no database involved. */
export type FoldedChain = {
    /** Every document the chain produces, by `_id`, in its final state. */
    docs: Record<string, Record<string, unknown>>;
    /** The class models among them, by class name. */
    classes: Record<string, ClassModel>;
    /** The versions folded, in the order they applied. */
    versions: string[];
    /** The highest version folded; `null` for an empty chain. */
    version: string | null;
};

/**
 * Whether a folded document is a class model.
 *
 * Deliberately shape-based and local: the fold runs over patch JSON with no stack, so it
 * cannot consult a registry, and `"~class": "class" | "~self"` is what the engine itself
 * recognises.
 *
 * @param doc - A folded document.
 * @returns `true` when the document describes a class.
 */
const isClassDoc = (doc: Record<string, unknown>): boolean =>
    doc["~class"] === "class" || doc["~class"] === "~self";

/**
 * Folds a patch chain into the documents it produces.
 *
 * This is the **baseline** an autogenerated patch diffs against (`proposal.md` §6.1):
 * the model the last patch leaves behind, computed from the patch files alone. It is a
 * pure function, so the CLI needs no database and cannot disagree with a device.
 *
 * The rules are the engine's own, not a second interpretation of them:
 * - patches apply in **semver order**, through the same comparator the engine sorts with;
 * - a document carrying `_rev: "auto"` **merges** over what the chain has produced so
 *   far, per-key for `schema` ({@link mergePatchSchema}) and per-field for everything
 *   else, which is what `applyPatch` and the ADR-0042 chain staging both do;
 * - any other document is stored **as authored**, the fresh-insert case;
 * - `_deleted` removes the document, so a chain that drops something folds to its
 *   absence rather than to a tombstone.
 *
 * @param patches - The chain, in any order.
 * @returns The folded chain; see {@link FoldedChain}.
 * @throws If a patch carries a version `semver` cannot parse, since an unordered chain
 * has no single baseline and guessing one would be worse than refusing.
 *
 * @example
 * ```typescript
 * const baseline = foldPatchChain(PATCHES);
 * baseline.classes.Todo.schema.title; // the attribute as the last patch leaves it
 * ```
 */
export const foldPatchChain = (patches: readonly Patch[]): FoldedChain => {
    for (const patch of patches) {
        if (!semver.valid(patch.version)) {
            throw new Error(
                `foldPatchChain - patch version '${patch.version}' is not valid semver, so the chain has no order.`
            );
        }
    }
    const ordered = [...patches].sort((left, right) => semver.compare(left.version, right.version));

    const docs: Record<string, Record<string, unknown>> = {};
    for (const patch of ordered) {
        for (const sourceDoc of patch.docs ?? []) {
            const id = (sourceDoc as { _id?: string })._id;
            if (!id) {
                throw new Error(
                    `foldPatchChain - patch '${patch.version}' carries a document with no '_id'.`
                );
            }
            if ((sourceDoc as { _deleted?: boolean })._deleted) {
                delete docs[id];
                continue;
            }
            let doc: Record<string, unknown> = { ...(sourceDoc as Record<string, unknown>) };
            if (doc._rev === "auto") {
                delete doc._rev;
                const existing = docs[id];
                if (existing) {
                    doc = { ...existing, ...doc };
                    delete doc._rev;
                    mergePatchSchema(sourceDoc, existing, doc);
                }
            }
            docs[id] = doc;
        }
    }

    const classes: Record<string, ClassModel> = {};
    for (const doc of Object.values(docs)) {
        if (!isClassDoc(doc)) continue;
        const name = typeof doc.name === "string" ? doc.name : (doc._id as string);
        classes[name] = doc as unknown as ClassModel;
    }

    const versions = ordered.map(patch => patch.version);
    return {
        docs,
        classes,
        versions,
        version: versions.length ? versions[versions.length - 1] : null,
    };
};
